package com.example.ui.screens

import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.text.KeyboardOptions
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.outlined.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.input.KeyboardType
import androidx.compose.ui.text.input.PasswordVisualTransformation
import com.asterreader.core.designsystem.AsterLayout
import com.example.ui.AsterUiState
import com.example.ui.AsterViewModel
import com.example.ui.components.*

/** 口令仅保留当前组合，不进入保存状态或导航参数。 */
@Composable
fun FileVaultContent(state: AsterUiState, model: AsterViewModel, section: String) {
    var password by remember(section, state.fileVaultOpen) { mutableStateOf("") }
    var confirmation by remember(section, state.fileVaultOpen) { mutableStateOf("") }
    var currentPassword by remember(section, state.fileVaultOpen) { mutableStateOf("") }
    var revealGenerated by remember(section, state.fileVaultOpen) { mutableStateOf(false) }
    var changing by remember(section, state.fileVaultOpen) { mutableStateOf(false) }
    var target by remember(section, state.fileVaultOpen) { mutableStateOf<android.net.Uri?>(null) }
    var restore by remember(section, state.fileVaultOpen) { mutableStateOf(false) }
    var acknowledged by remember(section, state.fileVaultOpen) { mutableStateOf(false) }
    DisposableEffect(Unit) { onDispose { password = ""; confirmation = ""; currentPassword = ""; target = null } }
    LaunchedEffect(state.isAppLockedNow, state.fileVaultOpen) {
        if (state.isAppLockedNow) { password = ""; confirmation = ""; currentPassword = ""; target = null }
    }
    val exportPicker = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/octet-stream")) {
        target = if (model.endFileVaultPicker()) it else null
    }
    val restorePicker = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) {
        target = if (model.endFileVaultPicker()) it else null; restore = target != null
    }
    val exporting = section.startsWith("fileExport:") && state.fileVaultOpen
    val creating = !state.fileVaultConfigured
    val credentials = !state.fileVaultOpen || exporting || restore || changing
    val newPassword = creating || exporting || changing
    val busy = state.fileVaultBusy

    if (busy) {
        LinearProgressIndicator(Modifier.fillMaxWidth())
        Text("正在加密或校验，请保持应用在前台", color = MaterialTheme.colorScheme.onSurfaceVariant, style = MaterialTheme.typography.bodySmall)
        TextButton(onClick = model::cancelFileVaultOperation) { Text("取消操作") }
    }
    state.fileVaultError?.let { Text(it, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }

    if (credentials) {
        AsterSettingsGroup(if (exporting) "导出口令" else if (restore) "文件口令" else if (changing) "新口令" else if (creating) "建立保险库" else "解锁保险库") {
            Column(Modifier.padding(AsterLayout.PagePadding), verticalArrangement = Arrangement.spacedBy(AsterLayout.ControlSpacing)) {
                if (changing) OutlinedTextField(currentPassword, { currentPassword = it.take(256) }, label = { Text("当前口令") },
                    singleLine = true, enabled = !busy, visualTransformation = PasswordVisualTransformation(),
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password), modifier = Modifier.fillMaxWidth())
                Text(when {
                    exporting -> "导出包含漫画、封面和阅读记录。使用独立长口令，忘记后无法恢复。"
                    restore -> "输入该导出文件的口令。验证全部密文后才导入。"
                    creating -> "本机保险库使用独立口令和设备密钥。卸载、清除数据或设备密钥丢失后，需要加密导出文件才能恢复。"
                    changing -> "修改本机口令，不会改变已导出文件的口令。"
                    else -> "输入保险库口令；应用 PIN 不能代替此口令。"
                }, color = MaterialTheme.colorScheme.onSurfaceVariant, style = MaterialTheme.typography.bodySmall)
                OutlinedTextField(password, { password = it.take(256); revealGenerated = false },
                    label = { Text("口令") }, singleLine = true, enabled = !busy,
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                    visualTransformation = if (revealGenerated) androidx.compose.ui.text.input.VisualTransformation.None else PasswordVisualTransformation(),
                    modifier = Modifier.fillMaxWidth())
                if (newPassword) {
                    OutlinedTextField(confirmation, { confirmation = it.take(256) }, label = { Text("确认口令") },
                        singleLine = true, enabled = !busy, visualTransformation = PasswordVisualTransformation(),
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password), modifier = Modifier.fillMaxWidth())
                    TextButton(enabled = !busy, onClick = {
                        model.generateFileVaultPassword { generated -> password = generated; confirmation = generated; revealGenerated = true }
                    }) { Icon(Icons.Outlined.Key, null, Modifier.size(AsterLayout.HeaderIconSize)); Spacer(Modifier.width(AsterLayout.ControlSpacing)); Text("生成随机口令") }
                    if (revealGenerated) Text("请安全保存显示的口令", color = MaterialTheme.colorScheme.primary, style = MaterialTheme.typography.bodySmall)
                    AsterSwitchRow("我已保存口令并了解恢复条件", checked = acknowledged, enabled = !busy, onCheckedChange = { acknowledged = it })
                }
                if (exporting && target == null) {
                    Button(onClick = { model.beginFileVaultPicker(); exportPicker.launch("aster-comic.astervault") }, enabled = !busy, modifier = Modifier.fillMaxWidth()) {
                        Icon(Icons.Outlined.SaveAlt, null); Spacer(Modifier.width(AsterLayout.ControlSpacing)); Text("选择保存位置")
                    }
                }
                Button(enabled = !busy && password.isNotEmpty() && (!newPassword || (password.length >= 12 && password == confirmation && acknowledged)) &&
                    (!exporting || target != null), modifier = Modifier.fillMaxWidth(), onClick = {
                    val chars = password.toCharArray()
                    password = ""; confirmation = ""; revealGenerated = false
                    when {
                        exporting -> { model.exportFileVaultBook(section.substringAfter(':'), target!!, chars); target = null }
                        restore -> { model.restoreFileVaultBook(target!!, chars); target = null; restore = false }
                        changing -> { model.changeFileVaultPassword(currentPassword.toCharArray(), chars); currentPassword = ""; changing = false }
                        else -> model.openFileVault(chars, creating)
                    }
                }) { Icon(if (exporting) Icons.Outlined.SaveAlt else Icons.Outlined.LockOpen, null); Spacer(Modifier.width(AsterLayout.ControlSpacing));
                    Text(if (exporting) "加密导出" else if (restore) "验证并恢复" else if (changing) "修改口令" else if (creating) "建立保险库" else "解锁") }
                if (restore || changing) TextButton(enabled = !busy, onClick = {
                    restore = false; changing = false; target = null
                    password = ""; confirmation = ""; currentPassword = ""; revealGenerated = false; acknowledged = false
                }) { Text("取消") }
            }
        }
    } else if (section == "fileEncrypt") {
        AsterSettingsGroup("加密文件") {
            Column(Modifier.padding(AsterLayout.PagePadding), verticalArrangement = Arrangement.spacedBy(AsterLayout.ControlSpacing)) {
                Text("漫画、封面、批注与进度将保存为密文。外部原文件仍保留，可能被其他应用读取。", color = MaterialTheme.colorScheme.onSurface, style = MaterialTheme.typography.bodyMedium)
                Text("需要额外存储空间。完成后清空搜索记录，请导出加密副本；取消或中断不会删除源文件。", color = MaterialTheme.colorScheme.onSurfaceVariant, style = MaterialTheme.typography.bodySmall)
                Button(onClick = model::encryptPendingBook, enabled = !busy, modifier = Modifier.fillMaxWidth()) {
                    Icon(Icons.Outlined.EnhancedEncryption, null); Spacer(Modifier.width(AsterLayout.ControlSpacing)); Text("加密并验证")
                }
            }
        }
    } else {
        AsterSettingsGroup("保险库已解锁") {
            AsterSettingsRow("恢复加密文件", leadingIcon = Icons.Outlined.FileOpen, onClick = {
                if (!busy) { model.beginFileVaultPicker(); restorePicker.launch(arrayOf("*/*")) }
            })
            AsterGroupDivider()
            AsterSettingsRow("验证完整性", leadingIcon = Icons.Outlined.VerifiedUser, onClick = { if (!busy) model.verifyFileVault() })
            AsterGroupDivider()
            AsterSettingsRow("修改口令", leadingIcon = Icons.Outlined.Key, onClick = { if (!busy) { changing = true; acknowledged = false } })
            AsterGroupDivider()
            AsterSettingsRow("锁定保险库", leadingIcon = Icons.Outlined.Lock, onClick = model::closeFileVault)
        }
        Text("作品详情中可加密或加密导出。请保留已验证的导出文件和口令。", color = MaterialTheme.colorScheme.onSurfaceVariant, style = MaterialTheme.typography.bodySmall)
    }
}
